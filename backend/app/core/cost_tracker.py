import os
from typing import List, Dict, Any, Optional
from pydantic import BaseModel, Field
from backend.app.core.config import settings
from backend.app.core.logging import logger


class CostItem(BaseModel):
    service: str  # "llm", "tts", "image_gen", "video_gen", "stock_media"
    provider: str  # "elevenlabs", "openai", "edge-tts", "pexels", "local"
    units: float  # characters, tokens, seconds, or calls
    unit_name: str  # "chars", "tokens", "images", "clips"
    cost_usd: float = 0.0


class AttributionRecord(BaseModel):
    asset_name: str
    asset_type: str  # "font", "music", "image", "sfx", "video"
    source_url_or_provider: str
    license_type: str  # "SIL Open Font License", "Royalty-Free Personal", "Pexels License"
    attribution_text: str


class CostAndAttributionTracker:
    def __init__(self, max_job_budget_usd: Optional[float] = None):
        self.max_budget = max_job_budget_usd or settings.job_max_budget_usd
        self.items: List[CostItem] = []
        self.attributions: List[AttributionRecord] = []
        self._add_builtin_attributions()

    def _add_builtin_attributions(self) -> None:
        """Register bundled open assets."""
        self.attributions.append(AttributionRecord(
            asset_name="Noto Sans Bengali",
            asset_type="font",
            source_url_or_provider="Google Fonts",
            license_type="SIL Open Font License 1.1",
            attribution_text="Noto Sans Bengali font is licensed under SIL Open Font License 1.1."
        ))
        self.attributions.append(AttributionRecord(
            asset_name="Ambient Music & SFX Bed",
            asset_type="audio",
            source_url_or_provider="AI Video Studio Synthesizer",
            license_type="CC0 / Free for personal & commercial use",
            attribution_text="Royalty-free ambient sound bed generated by AI Video Studio."
        ))

    def record_cost(self, item: CostItem) -> None:
        total = self.total_cost_usd() + item.cost_usd
        if total > self.max_budget:
            raise PermissionError(
                f"Operation halted: projected cost (${total:.2f}) exceeds configured job budget cap (${self.max_budget:.2f})."
            )
        self.items.append(item)
        logger.info(f"Recorded cost: {item.service} via {item.provider} = ${item.cost_usd:.4f} (Total: ${total:.4f})")

    def record_attribution(self, record: AttributionRecord) -> None:
        self.attributions.append(record)

    def total_cost_usd(self) -> float:
        return sum(item.cost_usd for item in self.items)

    def export_credits_file(self, output_path: str) -> str:
        """Generate credits and licensing text file."""
        lines = [
            "===========================================================",
            "             AI VIDEO STUDIO - CREDITS & ATTRIBUTION       ",
            "===========================================================",
            f"Total Production Cost: ${self.total_cost_usd():.4f} USD\n",
            "Services & Providers Used:"
        ]
        if not self.items:
            lines.append(" - 100% Free / Local open-source engines (Edge-TTS, Libass, Local FFmpeg).")
        else:
            for item in self.items:
                lines.append(f" - {item.service.upper()} ({item.provider}): {item.units} {item.unit_name} -> ${item.cost_usd:.4f}")

        lines.append("\nAsset Licensing & Attributions:")
        for attr in self.attributions:
            lines.append(f" • [{attr.asset_type.upper()}] {attr.asset_name} ({attr.source_url_or_provider})")
            lines.append(f"   License: {attr.license_type}")
            lines.append(f"   Note: {attr.attribution_text}\n")

        content = "\n".join(lines)
        with open(output_path, "w", encoding="utf-8") as f:
            f.write(content)
        return output_path
